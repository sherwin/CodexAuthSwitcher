import http from 'node:http';
import test from 'node:test';
import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createWeb } from '../proxy/web.mjs';
test('LAN web requires login and same-origin guarded mutations, exposes only approved routes', async t => {
 const directory=await fs.mkdtemp(path.join(os.tmpdir(),'switcher-web-'));
 const auth=path.join(directory,'auth');await fs.mkdir(auth);
 await fs.writeFile(path.join(directory,'proxy.json'),JSON.stringify({auth_directory:auth}));
 const calls=[]; const server=await createWeb({directory,password:'test-password-long-enough',host:'127.0.0.1',port:0,call:async(route,data)=>{calls.push([route,data]);return {ok:true}}});
 t.after(async()=>{server.closeAllConnections();await new Promise(r=>server.close(r));await fs.rm(directory,{recursive:true,force:true})});
 const base='http://127.0.0.1:'+server.address().port;
 const headers={Authorization:'Basic '+Buffer.from('admin:test-password-long-enough').toString('base64')};
 assert.equal((await fetch(base+'/')).status,401);
 assert.equal((await fetch(base+'/',{headers})).status,200);
 assert.equal((await fetch(base+'/api/accounts',{headers})).status,200);
 assert.equal(calls[0][0],'/admin/accounts');
 assert.equal((await fetch(base+'/api/auth-file',{method:'POST',headers,body:'{}'})).status,403);
 assert.equal((await fetch(base+'/api/auth-file',{method:'POST',headers:{...headers,Origin:'http://evil.test','X-Switcher-Web':'1'},body:'{}'})).status,403);
 assert.equal((await fetch(base+'/api/restore',{method:'POST',headers:{...headers,'X-Switcher-Web':'1'},body:'{}'})).status,404);
 const upload=(name)=>fetch(base+'/api/import',{method:'POST',headers:{...headers,'X-Switcher-Web':'1'},body:JSON.stringify({name,auth:{tokens:{access_token:'fake',refresh_token:'fake'}}})});
 assert.equal((await upload('../escape.json')).status,400);
 assert.equal((await upload('test.json')).status,200);
 assert.equal((await upload('test.json')).status,409);
 const rejected=await new Promise((resolve,reject)=>{http.get(base+'/api/status',{headers:{...headers,Host:'evil.test'}},r=>{r.resume();resolve(r.statusCode)}).on('error',reject)});
 assert.equal(rejected,403);
});
